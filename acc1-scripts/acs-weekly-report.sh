#!/bin/bash
# Layer 4: Weekly Report Generator
# Runs: Sunday at 4 AM via PM2
# Tokens: ~2000 (only layer using LLM)
# Generates: actionable recommendations for rule improvements

set -e

BASE_DIR="/root/workspaces/tools/acc1-scripts"
DATA_DIR="$BASE_DIR/data"
REPORTS_DIR="$BASE_DIR/reports"
HISTORY_DIR="$DATA_DIR/acs-history"
TODAY=$(date +%Y-%m-%d)
WEEK_AGO=$(date -d '7 days ago' +%Y-%m-%d 2>/dev/null || date -v-7d +%Y-%m-%d)
OUTPUT="$REPORTS_DIR/acs-weekly-$TODAY.md"

mkdir -p "$REPORTS_DIR"

# Aggregate 7 days of metrics
echo "Aggregating weekly data..."

# Collect all metrics from history
METRICS_SUMMARY=""
for i in $(seq 0 6); do
  DATE=$(date -d "$i days ago" +%Y-%m-%d 2>/dev/null || date -v-${i}d +%Y-%m-%d)
  METRICS_FILE="$HISTORY_DIR/$DATE/metrics-*.json"
  if ls $METRICS_FILE 1>/dev/null 2>&1; then
    # Get latest metrics for that day
    LATEST=$(ls -t $METRICS_FILE 2>/dev/null | head -1)
    if [ -f "$LATEST" ]; then
      METRICS_SUMMARY="$METRICS_SUMMARY
$(cat "$LATEST")"
    fi
  fi
done

# Get current compliance scores
OPUS_SCORE=$(redis-cli -n 2 HGET "acs:stats:agent:opus" compliance_score 2>/dev/null || echo 100)
SONNET_SCORE=$(redis-cli -n 2 HGET "acs:stats:agent:sonnet" compliance_score 2>/dev/null || echo 100)
HAIKU_SCORE=$(redis-cli -n 2 HGET "acs:stats:agent:haiku" compliance_score 2>/dev/null || echo 100)

# Get top violated rules this week
TOP_RULES=$(redis-cli -n 2 KEYS "acs:stats:rule:*" 2>/dev/null | while read key; do
  rule=$(echo "$key" | sed 's/acs:stats:rule://')
  count=$(redis-cli -n 2 GET "$key" 2>/dev/null || echo 0)
  [ -n "$count" ] && echo "$count $rule"
done | sort -rn | head -5)

# Generate report without LLM (basic version)
cat > "$OUTPUT" << EOF
# ACS Weekly Report: $WEEK_AGO — $TODAY

## Executive Summary

Generated: $(date -Iseconds)

### Compliance Scores
| Agent | Score |
|-------|-------|
| Opus | ${OPUS_SCORE}% |
| Sonnet | ${SONNET_SCORE}% |
| Haiku | ${HAIKU_SCORE}% |

### Top Violated Rules This Week

$(echo "$TOP_RULES" | awk '{printf "| %s | %d |\n", $2, $1}' | head -5)

---

## Data Sources

- Metrics: $HISTORY_DIR/*/metrics-*.json
- Hooks: $HISTORY_DIR/*/hooks-*.json
- Sessions: $HISTORY_DIR/*/sessions.json

---

## Raw Metrics Summary

\`\`\`
$METRICS_SUMMARY
\`\`\`

---

## Recommendations

> Note: For AI-generated recommendations, run:
> \`claude --print "Analyze this ACS report and suggest rule improvements: $(cat $OUTPUT)"\`

---

*Report generated by acs-weekly-report.sh*
EOF

echo "✅ Layer 4: Weekly report saved to $OUTPUT"
echo "   Run 'cat $OUTPUT' to view"
